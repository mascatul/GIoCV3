using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace GIoC.SourceGenerator;

/// <summary>
/// Roslyn incremental source generator.
///
/// For every partial class annotated with [Register], generates:
///
///   public override void _Ready()
///   {
///       base._Ready();
///       GodotIoC.Instance.InjectFields(this);
///       OnReady();
///   }
///   partial void OnReady();
///
/// This eliminates the need to manually call InjectFields(this) in _Ready().
/// Users put their _Ready() logic in OnReady() instead.
///
/// Usage:
///   [Register]
///   public partial class MyNode : Node3D
///   {
///       [Inject] private ScoreService _score;
///
///       partial void OnReady()
///       {
///           GD.Print(_score.Value); // already injected
///       }
///   }
/// </summary>
[Generator]
public sealed class RegisterGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classProvider = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax cls
                    && cls.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword))
                    && cls.AttributeLists.Count > 0,
                transform: static (ctx, _) => GetRegisterClassInfo(ctx))
            .Where(static x => x.HasValue)
            .Select(static (x, _) => x!.Value);

        context.RegisterSourceOutput(classProvider, static (spc, info) =>
        {
            var source = GenerateReadyMethod(info);
            spc.AddSource($"{info.ClassName}.Register.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static RegisterClassInfo? GetRegisterClassInfo(GeneratorSyntaxContext ctx)
    {
        var cls = (ClassDeclarationSyntax)ctx.Node;

        // Must be partial
        if (!cls.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)))
            return null;

        // Must have [Register] attribute
        bool hasRegister = false;
        foreach (var attrList in cls.AttributeLists)
        foreach (var attr in attrList.Attributes)
        {
            var name = attr.Name.ToString();
            if (name == "Register" || name == "RegisterAttribute")
            {
                hasRegister = true;
                break;
            }
        }
        if (!hasRegister) return null;

        // Get namespace
        var symbol = ctx.SemanticModel.GetDeclaredSymbol(cls) as INamedTypeSymbol;
        var ns = symbol?.ContainingNamespace?.IsGlobalNamespace == false
            ? symbol.ContainingNamespace.ToDisplayString()
            : null;

        return new RegisterClassInfo(cls.Identifier.Text, ns);
    }

    private static string GenerateReadyMethod(RegisterClassInfo info)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> Do not edit.");
        sb.AppendLine("// Generated by GIoC.SourceGenerator for [Register] classes.");
        sb.AppendLine("// Place your _Ready() logic in the generated OnReady() partial method.");
        sb.AppendLine();

        if (info.Namespace != null)
        {
            sb.AppendLine($"namespace {info.Namespace};");
            sb.AppendLine();
        }

        // IGIoCReadyCallback ensures OnReady() is only called AFTER all [Inject]
        // fields are filled — even when services are registered after this node's
        // _Ready() runs (e.g. pending injection resolved by AnnounceDependencyAvailable).
        sb.AppendLine($"partial class {info.ClassName} : global::GIoC.IGIoCReadyCallback");
        sb.AppendLine("{");
        sb.AppendLine("    public override void _Ready()");
        sb.AppendLine("    {");
        sb.AppendLine("        base._Ready();");
        sb.AppendLine("        global::GIoC.GodotIoC.Instance.InjectFields(this);");
        sb.AppendLine("        // OnReady() is called by GIoC via IGIoCReadyCallback.OnGIoCReady()");
        sb.AppendLine("        // once all [Inject] fields are filled (may be deferred if services");
        sb.AppendLine("        // are registered after this _Ready() call).");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    void global::GIoC.IGIoCReadyCallback.OnGIoCReady() => OnReady();");
        sb.AppendLine();
        sb.AppendLine("    partial void OnReady();");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private readonly struct RegisterClassInfo
    {
        public string  ClassName { get; }
        public string? Namespace { get; }

        public RegisterClassInfo(string className, string? ns)
        {
            ClassName = className;
            Namespace = ns;
        }
    }
}
